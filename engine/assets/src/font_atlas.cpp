const GlyphArt& glyph_art_for(char c) {
    const u32 code = static_cast<u32>(static_cast<unsigned char>(c));
    if (code < kFirstChar || code > kLastChar) {
        return kGlyphArt['?' - kFirstChar];
    }
    return kGlyphArt[code - kFirstChar];
}

u32 glyph_index_for(char c) {
    const u32 code = static_cast<u32>(static_cast<unsigned char>(c));
    if (code < kFirstChar || code > kLastChar) {
        return static_cast<u32>('?') - kFirstChar;
    }
    return code - kFirstChar;
}

