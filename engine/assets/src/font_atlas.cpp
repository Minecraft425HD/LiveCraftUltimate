// Real, own-design 5x7 dot-matrix glyph art for every printable ASCII
// character 32 ('  ') .. 126 ('~'), one entry per character in strict
// character-code order (index i here is character kFirstChar + i) -
// generate_glyph_pixels() below relies on that strict ordering to index
// straight into this array with no search. Each row is a 5-character
// string ('#' = an opaque pixel, '.' = transparent); 7 rows per glyph,
// rasterized into the top-left 5x7 of the real 6x8 glyph cell (the
// trailing 1px right column and 1px bottom row of every cell stay
// transparent spacing - see font_atlas.h). Plain geometric block-letter
// shapes, not a transcription of any real/existing font file (brief's
// own "no external font file, own design" requirement) - simple enough
// to reason about and hand-verify by inspection, not aiming for real
// typographic refinement.
struct GlyphArt {
    const char* rows[7];
};

