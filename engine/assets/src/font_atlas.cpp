GlyphUvRange glyph_uv_range(char c) {
    const u32 index = glyph_index_for(c);
    const u32 tx = index % kGlyphsPerRow;
    const u32 ty = index / kGlyphsPerRow;

    const f32 origin_u = static_cast<f32>(tx * kGlyphWidth);
    const f32 origin_v = static_cast<f32>(ty * kGlyphHeight);
    const f32 atlas_w = static_cast<f32>(kFontAtlasWidth);
    const f32 atlas_h = static_cast<f32>(kFontAtlasHeight);
    const f32 cell_w = static_cast<f32>(kGlyphWidth);
    const f32 cell_h = static_cast<f32>(kGlyphHeight);

    GlyphUvRange range;
    range.u0 = (origin_u + kGlyphInsetTexels) / atlas_w;
    range.v0 = (origin_v + kGlyphInsetTexels) / atlas_h;
    range.u1 = (origin_u + cell_w - kGlyphInsetTexels) / atlas_w;
    range.v1 = (origin_v + cell_h - kGlyphInsetTexels) / atlas_h;
    return range;
}

GlyphPixels generate_glyph_pixels(char c) {
    const GlyphArt& art = glyph_art_for(c);

    GlyphPixels pixels{};
    pixels.fill(0);
    for (u32 y = 0; y < kGlyphHeight; ++y) {
        for (u32 x = 0; x < kGlyphWidth; ++x) {
            const usize offset = (static_cast<usize>(y) * kGlyphWidth + x) * 4;
            // Real 5x7 glyph art lives in the top-left of the 6x8 cell;
            // the trailing 1px right column (x==5) and 1px bottom row
            // (y==7) are always transparent spacing - see the array's
            // own doc comment.
            const bool lit = (x < 5 && y < 7) && art.rows[y][x] == '#';
            if (lit) {
                pixels[offset + 0] = 255;
                pixels[offset + 1] = 255;
                pixels[offset + 2] = 255;
                pixels[offset + 3] = 255;
            }
        }
    }
    return pixels;
}

std::vector<u8> build_font_atlas_pixels() {
    std::vector<u8> atlas(static_cast<usize>(kFontAtlasWidth) * kFontAtlasHeight * 4, 0);

    for (u32 code = kFirstChar; code <= kLastChar; ++code) {
        const u32 index = code - kFirstChar;
        const u32 tx = index % kGlyphsPerRow;
        const u32 ty = index / kGlyphsPerRow;
        const GlyphPixels glyph = generate_glyph_pixels(static_cast<char>(code));

        for (u32 y = 0; y < kGlyphHeight; ++y) {
            for (u32 x = 0; x < kGlyphWidth; ++x) {
                const usize glyph_offset = (static_cast<usize>(y) * kGlyphWidth + x) * 4;
                const usize atlas_x = tx * kGlyphWidth + x;
                const usize atlas_y = ty * kGlyphHeight + y;
                const usize atlas_offset = (atlas_y * kFontAtlasWidth + atlas_x) * 4;
                std::memcpy(&atlas[atlas_offset], &glyph[glyph_offset], 4);
            }
        }
    }

    return atlas;
}

